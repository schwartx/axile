test('configuration motion stays inside the editor and moves the selection and remaining rows', async ({ page, request }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 1280, height: 800 })
  await request.patch('/api/v1/account/1', { data: { algorithm_schedule: [timeRule('09:30', '10:00'), timeRule('14:30', '15:00')] } })
  await page.goto('/e2e/futures-close.html')
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await expect(page.getByRole('button', { name: '编辑09:30 至 10:00', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.getAnimations().some(animation => (animation.effect as KeyframeEffect)?.pseudoElement))).toBe(false)
  const title = page.getByRole('heading', { level: 1 })
  const save = page.getByRole('button', { name: '保存', exact: true })
  const titleBounds = await title.boundingBox()
  const saveBounds = await save.boundingBox()
  await page.evaluate(() => {
    const start = document.startViewTransition.bind(document)
    document.startViewTransition = options => {
      const transition = start(options)
      void transition.ready.then(() => {
        const effects = document.getAnimations().flatMap(animation => {
          const effect = animation.effect as KeyframeEffect
          if (!effect?.pseudoElement) return []
          animation.pause()
          animation.currentTime = Number(effect.getTiming().duration) / 2
          return [{ pseudo: effect.pseudoElement, duration: effect.getTiming().duration,
            transforms: [...new Set(effect.getKeyframes().map(frame => frame.transform).filter(Boolean))] }]
        })
        document.documentElement.dataset.motionSample = JSON.stringify(effects)
      }).catch(error => { document.documentElement.dataset.motionSample = JSON.stringify({ error: String(error) }) })
      return transition
    }
  })
  const sample = async (action: () => Promise<unknown>, screenshot: string) => {
    await page.locator('html').evaluate(element => { delete element.dataset.motionSample })
    await action()
    await expect(page.locator('html')).toHaveAttribute('data-motion-sample')
    const effects = JSON.parse((await page.locator('html').getAttribute('data-motion-sample'))!) as { pseudo: string; duration: number; transforms: string[] }[]
    expect(Array.isArray(effects)).toBe(true)
    expect(effects.some(effect => effect.pseudo.includes('app-workspace'))).toBe(false)
    expect(effects.find(effect => effect.pseudo === '::view-transition-new(algorithm-parameters)')?.duration).toBe(150)
    expect(effects.some(effect => effect.pseudo === '::view-transition-group(algorithm-config-selection)' && effect.transforms.length > 1)).toBe(true)
    expect(await title.boundingBox()).toEqual(titleBounds)
    expect(await save.boundingBox()).toEqual(saveBounds)
    await page.screenshot({ path: testInfo.outputPath(screenshot), animations: 'allow' })
    await page.evaluate(() => document.getAnimations().forEach(animation => { if ((animation.effect as KeyframeEffect)?.pseudoElement) animation.finish() }))
    return effects
  }
  await sample(() => page.getByRole('button', { name: '编辑09:30 至 10:00', exact: true }).click(), 'algorithm-switch-midpoint.png')
  const deletion = await sample(() => page.getByRole('button', { name: '删除时段', exact: true }).click(), 'algorithm-delete-midpoint.png')
  expect(deletion.some(effect => effect.pseudo.startsWith('::view-transition-group(algorithm-item-') && effect.transforms.length > 1)).toBe(true)
  await expect(page.getByRole('button', { name: '编辑09:30 至 10:00', exact: true })).toHaveCount(0)
  await sample(() => page.getByRole('button', { name: '＋ 添加时段', exact: true }).click(), 'algorithm-add-midpoint.png')
  await expect(page.getByRole('group', { name: '开始时间', exact: true })).toBeVisible()
})

