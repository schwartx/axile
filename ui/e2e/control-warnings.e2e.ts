import { expect, test } from '@playwright/test'

const panel = (page: import('@playwright/test').Page) => page.getByRole('region', { name: /^流控预警/ })

test('crossing the threshold keeps focus, dismisses once, and alerts again at exhaustion', async ({ page }) => {
  await page.goto('/e2e/control-warnings.html')
  await page.getByRole('textbox', { name: '操作输入' }).focus()
  await page.evaluate(() => (document.querySelector('button') as HTMLButtonElement).click())
  await expect(panel(page)).toBeVisible()
  await expect(page.getByRole('textbox', { name: '操作输入' })).toBeFocused()
  await expect(panel(page)).toContainText('已达到 80% 预警线')
  const announced = await page.getByRole('status').textContent()
  const announcementMarkup = await page.getByRole('status').innerHTML()
  await page.getByRole('button', { name: '用量增加', exact: true }).click()
  await expect(panel(page)).toContainText('已用 85 / 100')
  expect(await page.getByRole('status').innerHTML()).toBe(announcementMarkup)
  await page.getByRole('button', { name: '关闭流控预警', exact: true }).click()
  await page.getByRole('button', { name: '达到预警线', exact: true }).click()
  await expect(panel(page)).toHaveCount(0)
  await expect(page.getByRole('region', { name: '账户摘要' })).toContainText('撤单额度预警')
  await page.getByRole('button', { name: '额度用尽', exact: true }).click()
  await expect(panel(page)).toContainText('额度已用尽')
  expect(await page.getByRole('status').textContent()).not.toBe(announced)
  await page.getByRole('button', { name: '额度用尽', exact: true }).click()
  await panel(page).getByRole('link', { name: '查看流控' }).click()
  await expect(page.locator('[data-route]')).toHaveText('/accounts/1/edit/control')
  await expect(panel(page)).toHaveCount(0)
})

test('initial catch-up survives refresh and starts again on a new control day', async ({ page }) => {
  await page.goto('/e2e/control-warnings.html?used=100')
  await expect(panel(page)).toContainText('额度已用尽')
  await page.reload()
  await expect(page.getByRole('heading', { name: '流控预警测试' })).toBeVisible()
  await expect(panel(page)).toHaveCount(0)
  await page.getByRole('button', { name: '新统计日', exact: true }).click()
  await expect(panel(page)).toContainText('额度预警')
})

test('stale snapshots retain last values and merge accounts without horizontal overflow', async ({ page }) => {
  await page.goto('/e2e/control-warnings.html?used=80')
  await expect(panel(page)).toContainText('已用 80 / 100')
  await page.getByRole('button', { name: '数据陈旧', exact: true }).click()
  await expect(panel(page)).toContainText('数据待更新')
  await expect(panel(page)).toContainText('已用 80 / 100')
  await page.getByRole('button', { name: '多账户预警', exact: true }).click()
  await expect(panel(page).getByRole('article')).toHaveCount(2)
  await expect(panel(page).getByRole('article').first()).toContainText('套利交易账户')
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await panel(page).evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '全部关闭', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(panel(page)).toHaveCount(0)
})

test('Web Locks and persistent records prevent a second tab from claiming the same alert', async ({ page, context }) => {
  await page.goto('/e2e/control-warnings.html?used=80')
  await expect(panel(page)).toBeVisible()
  const other = await context.newPage()
  await other.goto('/e2e/control-warnings.html?used=80')
  await other.bringToFront()
  await expect(other.getByRole('heading', { name: '流控预警测试' })).toBeVisible()
  await expect(panel(other)).toHaveCount(0)
  await other.getByRole('button', { name: '额度用尽', exact: true }).click()
  await expect(panel(other)).toContainText('额度已用尽')
  await page.bringToFront()
  await page.getByRole('button', { name: '额度用尽', exact: true }).click()
  // 原面板更新当前状态，但不再次播报其他标签页已领取的阶段。
  await expect(panel(page)).toContainText('额度已用尽')
  await expect(page.getByRole('status')).not.toContainText('额度已用尽')
})

test('the new panel stays below modal dialogs and warnings do not depend on selected metrics', async ({ page }) => {
  await page.goto('/e2e/control-warnings.html')
  await page.evaluate(() => localStorage.setItem(`axile:control:${location.origin}:1`, JSON.stringify(['account:query_order:per_day'])))
  await page.reload()
  await page.getByRole('button', { name: '达到预警线', exact: true }).click()
  await expect(page.getByRole('region', { name: '账户摘要' })).toContainText('撤单额度预警')
  await page.getByRole('button', { name: '打开确认弹窗', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '确认操作' })
  await expect(modal).toBeVisible()
  const panelZ = await panel(page).evaluate(element => Number(getComputedStyle(element).zIndex))
  expect(await modal.evaluate(element => Number(getComputedStyle(element).zIndex))).toBeGreaterThan(panelZ)
  await page.keyboard.press('Escape')
  await expect(modal).toBeHidden()
  await expect(panel(page)).toBeVisible()
})
