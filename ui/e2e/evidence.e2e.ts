/** 故意忽略 abort 的传输，覆盖取消后迟到响应与新请求并存的竞态。 */
async function delayedTransport(page: Page) {
  await page.addInitScript(() => {
    const original = window.fetch
    const pending: { signal: AbortSignal; resolve: (response: Response) => void }[] = []
    Object.assign(window, { evidencePending: pending })
    window.fetch = (input, init) => String(input).includes('/evidence?')
      ? new Promise<Response>(resolve => pending.push({ signal: init!.signal!, resolve })) : original(input, init)
  })
}
async function release(page: Page, index: number) {
  await page.evaluate(async index => {
    const pending = (window as unknown as { evidencePending: { resolve: (response: Response) => void }[] }).evidencePending
    pending[index].resolve(new Response('PK synthetic evidence', { headers: { 'Content-Type': 'application/zip' } }))
    // 等待 fetch、blob、提交处理器的微任务全部完成，作为迟到响应的观察点。
    await new Promise(resolve => setTimeout(resolve, 0))
  }, index)
}
async function pendingState(page: Page) {
  return page.evaluate(() => (window as unknown as { evidencePending: { signal: AbortSignal }[] }).evidencePending.map(item => item.signal.aborted))
}

test('cancel aborts, blocks double submission, and a late response cannot download or reset a new request', async ({ page }) => {
  await delayedTransport(page)
  await defaults(page)
  const downloads: string[] = []
  page.on('download', file => downloads.push(file.suggestedFilename()))
  await visit(page)
  const opener = page.getByRole('button', { name: '导出本次证据', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '导出本次证据' })
  await dialog.locator('form').evaluate((form: HTMLFormElement) => { form.requestSubmit(); form.requestSubmit() })
  await expect.poll(() => pendingState(page)).toEqual([false])
  await expect(dialog.getByRole('checkbox')).toBeDisabled()
  await expect(dialog.getByRole('button', { name: '内部诊断', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '取消下载' }).click()
  await expect(opener).toBeFocused()
  await expect.poll(() => pendingState(page)).toEqual([true])
  await opener.click()
  await dialog.getByRole('button', { name: '生成并下载 ZIP' }).click()
  await expect.poll(() => pendingState(page)).toEqual([true, false])
  await release(page, 0)
  expect(downloads).toEqual([])
  await expect(dialog.getByRole('button', { name: '正在生成…' })).toBeDisabled()
  await expect(dialog.getByRole('status').filter({ hasText: '证据导出失败' })).toHaveCount(0)
  const download = page.waitForEvent('download')
  await release(page, 1)
  await download
  expect(downloads).toEqual(['axile-evidence-execution-A.zip'])
})

