import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const zip = Buffer.from('UEsFBgAAAAAAAAAAAAAAAAAAAAAAAA==', 'base64')
async function defaults(page: Page, status = 'RUNNING', owner = 7) {
  await page.route('**/api/v1/**', async route => {
    const path = new URL(route.request().url()).pathname
    if (path.endsWith('/evidence')) return route.fulfill({ body: zip, contentType: 'application/zip' })
    if (/\/executions\/[AB]$/.test(path)) return route.fulfill({ json: { execution_id: path.split('/').at(-1), account_id: owner, execution_kind: 'rebalance', status, created_at: '2026-10-15T10:00:00', started_at: null, finished_at: null, error_message: null } })
    return route.fulfill({ json: { data: [], count: 0, snapshot_id: 'snapshot-test', next_cursor: null } })
  })
}
async function visit(page: Page, entry = '/accounts/7/executions/A') {
  await page.goto('/e2e/evidence.html?' + new URLSearchParams({ entry }))
}
