import { expect, test } from '@playwright/test'

test('advanced transfer controls preserve ranges, scheduling, retention and the system draft', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  let plan: Record<string, unknown> = {}
  let systemSaves = 0
  await page.route('**/api/v1/init/save', route => { systemSaves++; return route.fulfill({ json: { ok: true } }) })
  await page.route('**/api/v1/transfer/settings', route => {
    if (route.request().method() === 'PUT') {
      plan = route.request().postDataJSON()
      return route.fulfill({ json: { saved: true } })
    }
    return route.fulfill({ json: { plan, last_run: null } })
  })
  await page.route('**/api/v1/transfer/export', route => route.fulfill({ body: 'fixture-package' }))
  await page.goto('/e2e/data-transfer.html')
  const database = page.getByPlaceholder('已配置 · 留空保持不变')
  await database.fill('sqlite+aiosqlite:///./unsaved.db')
  const opener = page.getByRole('button', { name: '打开数据传送' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '数据传送', exact: true })
  const save = dialog.getByRole('button', { name: '保存规则' })
  const range = dialog.getByRole('button', { name: '指定范围', exact: true })
  const automatic = dialog.getByRole('switch', { name: '自动拉取' })
  const days = dialog.getByRole('textbox', { name: '执行记录保留天数' })
  await expect(save).toBeEnabled()
  await expect(automatic).not.toBeChecked()
  await expect(days).toHaveAttribute('placeholder', '不清理')
  await expect(days).toHaveValue('')
  await automatic.click()
  await expect(save).toBeDisabled()
  await expect(dialog.getByRole('alert')).toHaveText('自动拉取需要填写来源端地址')
  await automatic.click()
  await dialog.getByLabel('来源端地址').fill('https://source.test')
  await range.click()
  const start = dialog.getByRole('textbox', { name: '开始日期', exact: true })
  const end = dialog.getByRole('textbox', { name: '结束日期', exact: true })
  await start.fill('2020-01-01')
  await end.fill('2020-02-01')
  await dialog.getByRole('button', { name: '开始日期，打开日历' }).click()
  await page.getByRole('button', { name: '2020-01-02', exact: true }).click()
  await expect(start).toHaveValue('2020-01-02')
  const time = dialog.getByRole('group', { name: '开始时刻', exact: true })
  await time.getByRole('button', { name: '时', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '选择时刻', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await expect(page.getByRole('dialog', { name: '选择时刻', exact: true })).toBeHidden()
  await time.focus()
  await time.press('ArrowUp')
  await time.press('ArrowRight')
  await time.press('ArrowUp')

  await automatic.click()
  const interval = dialog.getByRole('group', { name: '拉取间隔输入', exact: true })
  const intervalDays = interval.getByRole('textbox', { name: '拉取间隔：天', exact: true })
  const hours = interval.getByRole('textbox', { name: '拉取间隔：小时', exact: true })
  await hours.fill('23')
  await hours.press('Enter')
  const flows = interval.locator('number-flow-react')
  await expect(flows).toHaveCount(2)
  await expect.poll(() => flows.evaluateAll(nodes => nodes.every(node => node.shadowRoot!.getAnimations().length === 0))).toBe(true)
  await flows.evaluateAll(nodes => nodes.forEach(node => node.addEventListener('animationsstart', () => { (node as HTMLElement).dataset.started = 'true' })))
  await interval.getByRole('button', { name: '拉取间隔：增加 1 小时', exact: true }).click()
  await expect(intervalDays).toHaveValue('1')
  await expect(hours).toHaveValue('0')
  await expect.poll(() => flows.evaluateAll(nodes => nodes.every(node => (node as HTMLElement).dataset.started === 'true'))).toBe(true)
  await interval.getByRole('button', { name: '拉取间隔：减少 1 小时', exact: true }).click()
  await expect(intervalDays).toHaveValue('0')
  await expect(hours).toHaveValue('23')

  await hours.fill('1')
  await expect(interval.getByRole('button', { name: '拉取间隔：减少 1 小时', exact: true })).toBeDisabled()
  await intervalDays.fill('365')
  await hours.fill('0')
  await expect(interval.getByRole('button', { name: '拉取间隔：增加 1 小时', exact: true })).toBeDisabled()
  await intervalDays.focus()
  await expect(interval.getByRole('button', { name: '拉取间隔：增加 1 天', exact: true })).toBeDisabled()
  await intervalDays.fill('1')
  await hours.fill('2')
  await intervalDays.focus()
  await intervalDays.press('ArrowUp')
  await expect(intervalDays).toHaveValue('2')
  await expect(hours).toHaveValue('2')
  await intervalDays.press('ArrowDown')
  await expect(intervalDays).toHaveValue('1')

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect.poll(() => flows.evaluateAll(nodes => nodes.every(node => node.shadowRoot!.getAnimations().length === 0))).toBe(true)
  await flows.evaluateAll(nodes => nodes.forEach(node => { delete (node as HTMLElement).dataset.started }))
  await hours.focus()
  await interval.getByRole('button', { name: '拉取间隔：增加 1 小时', exact: true }).click()
  await expect(hours).toHaveValue('3')
  await page.evaluate(async () => { await new Promise(requestAnimationFrame); await new Promise(requestAnimationFrame) })
  expect(await flows.evaluateAll(nodes => nodes.every(node => !(node as HTMLElement).dataset.started && node.shadowRoot!.getAnimations().length === 0))).toBe(true)
  await hours.fill('2')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await dialog.getByRole('group', { name: '执行记录保留', exact: true }).getByRole('button', { name: /增加/ }).click()
  await expect(days).toHaveValue('1')
  await days.fill('1.5')
  await expect(save).toBeDisabled()
  await expect(dialog.getByRole('alert')).toContainText('保留天数需为正整数')
  await days.fill('7')
  await save.click()
  await expect(dialog.getByRole('status')).toHaveText('传送规则已保存')
  expect(plan).toMatchObject({ start: '2020-01-02T01:01:00+08:00', end: '2020-02-01T00:00:00+08:00', every_hours: 26, execution_days: 7, replay_days: null })
  await page.screenshot({ path: test.info().outputPath('transfer-desktop.png'), animations: 'disabled' })
  await interval.screenshot({ path: test.info().outputPath('duration-stepper.png'), animations: 'disabled' })
  await dialog.getByRole('button', { name: '离线传送', exact: true }).click()
  const download = page.waitForEvent('download')
  await dialog.getByRole('button', { name: '导出数据包' }).click()
  expect((await download).suggestedFilename()).toBe('data.axile')

  let request: Record<string, unknown> = {}
  let finishPull = () => {}
  const pulling = new Promise<void>(resolve => { finishPull = resolve })
  await page.route('**/api/v1/transfer/pull', async route => {
    request = route.request().postDataJSON()
    await pulling
    return route.fulfill({ json: { batch: 'pulled-batch' } })
  })
  await dialog.getByRole('button', { name: '立即拉取' }).click()
  const close = dialog.getByRole('button', { name: '关闭', exact: true })
  await expect(close).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  finishPull()
  await expect(dialog.getByRole('status')).toHaveText('拉取完成 · pulled-batch')
  expect(request.source_url).toBe('https://source.test')
  await close.click()
  await expect(dialog).toBeHidden()
  await expect(opener).toBeFocused()
  await expect(database).toHaveValue('sqlite+aiosqlite:///./unsaved.db')
  expect(systemSaves).toBe(0)

  await page.reload()
  await opener.click()
  await expect(range).toHaveAttribute('aria-pressed', 'true')
  await expect(start).toHaveValue('2020-01-02')
  await expect(end).toHaveValue('2020-02-01')
  await expect(automatic).toBeChecked()
  await expect(intervalDays).toHaveValue('1')
  await expect(hours).toHaveValue('2')
  await expect(days).toHaveValue('7')
  await dialog.getByRole('button', { name: '全部数据', exact: true }).click()
  await automatic.click()
  await days.fill('')
  await save.click()
  await expect(dialog.getByRole('status')).toHaveText('传送规则已保存')
  expect(plan).toMatchObject({ start: null, end: null, every_hours: 0, execution_days: null, replay_days: null })
  expect(systemSaves).toBe(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(async () => (await dialog.boundingBox())!.x).toBeGreaterThanOrEqual(0)
  const bounds = await dialog.boundingBox()
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: test.info().outputPath('transfer-mobile.png'), animations: 'disabled' })
  await range.click()
  await automatic.click()
  await expect(intervalDays).toHaveValue('1')
  await expect(hours).toHaveValue('2')
  await start.scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('transfer-mobile-expanded.png'), animations: 'disabled' })
})
