import { expect, test } from '@playwright/test'

test('共用画布保留账户选区、缩放和每日模式，品种保留分段读数和固定身份色', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1200 })
  await page.goto('/e2e/performance-chart.html')
  const account = page.getByTestId('performance-chart'), contribution = page.getByTestId('contribution-chart')
  await expect(page.locator('[data-chart="time-series"]')).toHaveCount(2)
  await expect(account).toBeVisible()
  await account.focus()
  await account.press('Home')
  await expect(page.locator('#performance-keyboard-reading')).toContainText('账户 0.00%')
  await account.press('Enter')
  await expect(page.getByTestId('selection')).toContainText('"kind":"day"')
  await account.press('ArrowRight')
  await account.press('Enter')
  await expect(page.getByTestId('selection')).toContainText('"kind":"interval"')
  await account.press('Escape')
  await expect(page.getByTestId('selection')).toHaveText('null')
  const full = await page.getByTestId('chart-viewport').textContent()
  await account.press('+')
  await expect(page.getByTestId('chart-viewport')).not.toHaveText(full!)
  await account.press('0')
  await expect(page.getByTestId('chart-viewport')).toHaveText(full!)
  await account.dispatchEvent('wheel', { ctrlKey: true, deltaY: -100, clientX: 400 })
  await expect(page.getByTestId('chart-viewport')).not.toHaveText(full!)
  await account.dblclick({ position: { x: 300, y: 120 } })
  await expect(page.getByTestId('chart-viewport')).toHaveText(full!)
  const bounds = (await account.boundingBox())!
  await account.click({ position: { x: 12 + (bounds.width - 90) * 0.6, y: 120 } })
  await expect(page.getByTestId('selection')).toContainText('"kind":"execution","recordId":4')
  await account.press('Escape')
  await page.mouse.move(bounds.x + 80, bounds.y + 200)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 500, bounds.y + 200, { steps: 4 })
  await page.mouse.up()
  await expect(page.getByTestId('selection')).toContainText('"kind":"interval"')
  await account.press('Escape')

  await contribution.focus()
  await contribution.press('Home')
  await expect(page.locator('#contribution-reading')).toContainText('2026-10-01')
  await contribution.press('End')
  await expect(page.locator('#contribution-reading')).toContainText('+13,000')
  await expect(page.locator('#contribution-reading')).toContainText('本段盈亏 -5,000')
  const checkbox = page.getByLabel('查看 SHFE.fu 贡献曲线')
  const color = await checkbox.evaluate(input => getComputedStyle(input).color)
  await expect(checkbox).toHaveCSS('appearance', 'none')
  await expect(checkbox).toHaveCSS('background-color', color)
  await checkbox.focus()
  await checkbox.press('Space')
  await expect(checkbox).not.toBeChecked()
  await expect(checkbox).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await checkbox.locator('..').locator('..').locator('.overflow-text-static').click()
  await expect(checkbox).toBeChecked()
  await page.getByLabel('查看 DCE.c 贡献曲线').uncheck()
  await expect(checkbox).toHaveCSS('background-color', color)
  await contribution.focus()
  await contribution.press('+')
  await contribution.press('Home')
  await contribution.press('0')
  await page.getByRole('button', { name: '切换主题' }).click()
  await page.getByRole('button', { name: '切换时间轴' }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(checkbox).toBeChecked()
  await expect(checkbox).toHaveCSS('background-color', await checkbox.evaluate(input => getComputedStyle(input).color))
  await page.getByLabel('查看 DCE.c 贡献曲线').check()
  await page.getByRole('button', { name: '切换每日' }).click()
  await expect(account).toHaveAttribute('aria-label', '每日收益与执行成本')
  await page.getByRole('button', { name: '切换每日' }).click()
  for (const width of [740, 1440]) {
    await page.setViewportSize({ width, height: 1200 })
    await expect.poll(() => account.evaluate(canvas => canvas.width / devicePixelRatio - canvas.clientWidth)).toBe(0)
    await expect.poll(() => contribution.evaluate(canvas => canvas.width / devicePixelRatio - canvas.clientWidth)).toBe(0)
  }
  await page.screenshot({ path: testInfo.outputPath('shared-charts.png'), fullPage: true })
  expect(errors).toEqual([])
})
