import { expect, test } from '@playwright/test'

test('切换表达式和时间字段保留模式控件，逐帧保持编辑区可见', async ({ page }) => {
  await page.goto('/e2e/cron-setting.html')
  await page.getByRole('button', { name: '设置定时', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '定时任务设置' })
  const raw = dialog.getByRole('textbox', { name: '当前表达式', exact: true })
  await raw.fill('*/5 9 * * *')
  await dialog.getByRole('button', { name: '添加表达式', exact: true }).click()
  await raw.fill('*/10 9 * * *')
  await dialog.getByRole('button', { name: '添加表达式', exact: true }).click()
  await raw.fill('* 9 * * *')
  const panel = dialog.getByRole('tabpanel')
  const modeNode = await panel.getByRole('radiogroup').elementHandle()
  for (const switchItem of [
    () => dialog.getByRole('button', { name: '编辑表达式 1', exact: true }).click(),
    () => dialog.getByRole('button', { name: '编辑表达式 2', exact: true }).click(),
    () => dialog.getByRole('button', { name: '编辑表达式 3', exact: true }).click(),
    () => dialog.getByRole('tab', { name: '小时', exact: true }).click(),
    () => dialog.getByRole('tab', { name: '分钟', exact: true }).click(),
  ]) {
    await switchItem()
    expect(await modeNode!.evaluate((node) => node.isConnected)).toBe(true)
    const opacity = await panel.evaluate(async (node) => {
      const modes = node.querySelector('[role="radiogroup"]')!
      const nodes = [node, node.firstElementChild!, modes, modes.nextElementSibling!]
      let minimum = 1
      for (let frame = 0; frame < 12; frame++) {
        await new Promise(requestAnimationFrame)
        minimum = Math.min(minimum, ...nodes.map((element) => Number(getComputedStyle(element).opacity)))
      }
      return minimum
    })
    expect(opacity).toBe(1)
  }
})

test('常用表达式支持搜索并通过键盘选取回填', async ({ page }) => {
  await page.goto('/e2e/cron-setting.html')
  await page.getByRole('button', { name: '设置定时', exact: true }).click()
  await page.getByRole('button', { name: '选择常用表达式', exact: true }).click()
  const search = page.getByRole('textbox', { name: '搜索选项', exact: true })
  await expect(search).toBeFocused()
  await search.fill('每周一')
  await expect(page.getByRole('option')).toHaveCount(1)
  await expect(page.getByRole('option')).toContainText('每周一9点30分')
  await search.press('Enter')
  await expect(page.getByRole('textbox', { name: '当前表达式', exact: true })).toHaveValue('30 9 * * 0')
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByLabel('保存的表达式')).toHaveText('30 9 * * 0')
})

test('空选阻止保存，键盘多选只占一个 Tab 位置，确认与取消隔离', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/e2e/cron-setting.html')
  await page.getByRole('button', { name: '设置定时', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '定时任务设置' })
  await expect(dialog.getByRole('tabpanel')).toHaveCSS('animation-name', 'none')
  const grid = dialog.getByRole('group', { name: '选择分钟', exact: true })
  await expect(grid.getByRole('checkbox', { checked: true })).toHaveCount(1)
  await expect(grid.getByRole('checkbox', { name: '59分', exact: true })).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('cron-dark-grid.png'), animations: 'disabled' })
  await dialog.getByRole('button', { name: '清空', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await expect(dialog.getByRole('alert').filter({ hasText: '请至少选择一项' }).last()).toBeVisible()
  expect(await grid.getByRole('checkbox').evaluateAll((buttons) => buttons.filter((button) => (button as HTMLElement).tabIndex === 0).length)).toBe(1)
  await grid.getByRole('checkbox', { name: '0分', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(grid.getByRole('checkbox', { name: '10分', exact: true })).toBeFocused()
  await page.keyboard.press('Space')
  await expect(grid.getByRole('checkbox', { name: '10分', exact: true })).toBeChecked()
  await page.keyboard.press('Tab')
  expect(await grid.evaluate((node) => node.contains(document.activeElement))).toBe(false)
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByLabel('保存的表达式')).toHaveText('10 9 * * 0')
  await page.getByRole('button', { name: '设置定时', exact: true }).click()
  await dialog.getByRole('radio', { name: '每分钟', exact: true }).click()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByLabel('保存的表达式')).toHaveText('10 9 * * 0')
  await expect(page.getByRole('button', { name: '设置定时', exact: true })).toBeFocused()
})

test('模式与字段切换保留草稿，非当前模式不占焦点，数字支持直接编辑与边界', async ({ page }) => {
  await page.goto('/e2e/cron-setting.html')
  await page.getByRole('button', { name: '设置定时', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '定时任务设置' })
  const start = dialog.getByLabel('分钟间隔起始值', { exact: true })
  const step = dialog.getByRole('textbox', { name: '分钟间隔', exact: true })
  await dialog.getByRole('radio', { name: '按间隔', exact: true }).click()
  await start.fill('1')
  await step.fill('4')
  await step.press('ArrowUp')
  await expect(step).toHaveValue('5')
  await step.press('ArrowDown')
  await expect(step).toHaveValue('4')
  await dialog.getByRole('radio', { name: '按间隔', exact: true }).press('ArrowRight')
  await expect(dialog.getByRole('radio', { name: '范围', exact: true })).toBeChecked()
  await dialog.getByRole('textbox', { name: '分钟范围起始值', exact: true }).fill('10')
  await dialog.getByRole('textbox', { name: '分钟结束值', exact: true }).fill('20')
  await expect(start).toHaveCount(0)
  await dialog.getByRole('tab', { name: '小时', exact: true }).click()
  await expect(dialog.getByRole('tabpanel')).toHaveCSS('animation-name', 'none')
  await dialog.getByRole('tab', { name: '小时', exact: true }).press('ArrowLeft')
  await expect(dialog.getByRole('tab', { name: '分钟', exact: true })).toBeFocused()
  await dialog.getByRole('radio', { name: '按间隔', exact: true }).click()
  await expect(start).toHaveValue('1')
  await expect(step).toHaveValue('4')
  await dialog.getByRole('radio', { name: '范围', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: '分钟范围起始值', exact: true })).toHaveValue('10')
  await expect(dialog.getByRole('textbox', { name: '分钟结束值', exact: true })).toHaveValue('20')
  await dialog.getByRole('radio', { name: '按间隔', exact: true }).click()
  await start.fill('58')
  await step.fill('1')
  await expect(step.locator('xpath=../../..').getByRole('button', { name: '增加 1', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByLabel('保存的表达式')).toHaveText('58/1 9 * * 0')
})

test('窄屏与减少动态效果保持键盘可用，无横向溢出', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/e2e/cron-setting.html')
  await page.getByRole('button', { name: '设置定时', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '定时任务设置' })
  const grid = dialog.getByRole('group', { name: '选择分钟', exact: true })
  await grid.getByRole('checkbox', { name: '0分', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(grid.getByRole('checkbox', { name: '6分', exact: true })).toBeFocused()
  await page.keyboard.press('Space')
  await expect(grid.getByRole('checkbox', { name: '6分', exact: true })).toBeChecked()
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('cron-narrow.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: '设置定时', exact: true })).toBeFocused()
})

test('明暗主题下横排选择器稳定，参数区局部切换，减少动态效果可关闭', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/e2e/cron-setting.html')
  await page.getByRole('button', { name: '设置定时', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '定时任务设置' })
  const tabs = dialog.getByRole('tablist', { name: '时间字段' })
  const modes = dialog.getByRole('radiogroup', { name: '分钟设置方式' })
  const anchor = await tabs.boundingBox()
  const modeAnchor = await modes.boundingBox()
  const rows = await modes.getByRole('radio').evaluateAll((buttons) => buttons.map((button) => button.getBoundingClientRect().top))
  expect(new Set(rows).size).toBe(1)
  await dialog.getByRole('radio', { name: '按间隔', exact: true }).click()
  const parameters = modes.locator('xpath=following-sibling::div[1]')
  await expect(parameters).toHaveCSS('animation-name', 'panel-fade-in')
  const start = dialog.getByLabel('分钟间隔起始值', { exact: true })
  await start.fill('1')
  await dialog.getByLabel('分钟间隔', { exact: true }).fill('4')
  await dialog.getByRole('radio', { name: '按间隔', exact: true }).focus()
  await expect(tabs.locator(':scope > span')).toHaveCSS('transition-duration', '0.2s')
  expect(await tabs.boundingBox()).toEqual(anchor)
  expect(await modes.boundingBox()).toEqual(modeAnchor)
  for (const theme of ['dark', 'light']) {
    await page.evaluate((theme) => document.documentElement.classList.toggle('dark', theme === 'dark'), theme)
    await expect(start).toHaveValue('1')
    expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`cron-${theme}-interval.png`), animations: 'disabled' })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await dialog.getByRole('radio', { name: '范围', exact: true }).click()
  await expect(parameters).toHaveCSS('animation-name', 'none')
  await expect(tabs.locator(':scope > span')).toHaveCSS('transition-property', 'none')
})
